-- globalGOV first-party operations, evidence archive and recovery metadata.
-- PostgreSQL 17+. All writes are owner-controlled; no public route mutates these tables.
BEGIN;

CREATE TABLE IF NOT EXISTS source_policy_reviews (
  source_id TEXT PRIMARY KEY,
  automated_access_status TEXT NOT NULL
    CHECK (automated_access_status IN ('approved', 'research_only', 'clarification_required', 'denied', 'not_assessed')),
  reuse_status TEXT NOT NULL
    CHECK (reuse_status IN ('approved', 'conditional', 'review_required', 'not_approved', 'not_assessed')),
  permitted_methods JSONB NOT NULL DEFAULT '[]'::jsonb,
  allowed_hosts TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
  policy_url TEXT,
  reviewed_at BIGINT,
  expires_at BIGINT,
  reviewer_label TEXT,
  notes TEXT NOT NULL DEFAULT '',
  updated_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS source_policy_expiry ON source_policy_reviews(expires_at);

CREATE TABLE IF NOT EXISTS source_connector_runs (
  id TEXT PRIMARY KEY,
  source_id TEXT NOT NULL,
  started_at BIGINT NOT NULL,
  finished_at BIGINT NOT NULL,
  state TEXT NOT NULL CHECK (state IN ('ok', 'blocked', 'rejected', 'error', 'no_change')),
  automation_status TEXT NOT NULL,
  http_status INTEGER,
  fetched_bytes BIGINT NOT NULL DEFAULT 0,
  documents_found INTEGER NOT NULL DEFAULT 0,
  notices_candidate INTEGER NOT NULL DEFAULT 0,
  accepted INTEGER NOT NULL DEFAULT 0,
  rejected INTEGER NOT NULL DEFAULT 0,
  source_url TEXT NOT NULL,
  response_sha256 CHAR(64),
  error_code TEXT,
  details JSONB NOT NULL DEFAULT '{}'::jsonb
);
CREATE INDEX IF NOT EXISTS source_connector_runs_recent ON source_connector_runs(source_id, started_at DESC);
CREATE INDEX IF NOT EXISTS source_connector_runs_state ON source_connector_runs(state, started_at DESC);

CREATE TABLE IF NOT EXISTS source_documents (
  sha256 CHAR(64) PRIMARY KEY CHECK (sha256 ~ '^[a-f0-9]{64}$'),
  source_id TEXT NOT NULL,
  source_url TEXT NOT NULL,
  storage_key TEXT NOT NULL UNIQUE,
  content_type TEXT NOT NULL CHECK (content_type IN ('application/pdf')),
  byte_length BIGINT NOT NULL CHECK (byte_length > 0 AND byte_length <= 10485760),
  first_seen_at BIGINT NOT NULL,
  last_seen_at BIGINT NOT NULL,
  provenance TEXT NOT NULL CHECK (provenance IN ('official_https_fetch', 'founder_supplied_local_document')),
  review_state TEXT NOT NULL CHECK (review_state IN ('requires_review', 'reviewed', 'rejected')),
  text_sha256 CHAR(64),
  evidence JSONB NOT NULL DEFAULT '{}'::jsonb
);
CREATE INDEX IF NOT EXISTS source_documents_source_seen ON source_documents(source_id, last_seen_at DESC);

CREATE TABLE IF NOT EXISTS manual_review_queue (
  id TEXT PRIMARY KEY,
  source_id TEXT NOT NULL,
  document_sha256 CHAR(64) REFERENCES source_documents(sha256) ON DELETE RESTRICT,
  record_type TEXT NOT NULL CHECK (record_type IN ('recruitment_notice', 'admit_card', 'exam_schedule', 'result', 'corrigendum', 'cancellation', 'other')),
  evidence JSONB NOT NULL,
  state TEXT NOT NULL DEFAULT 'pending' CHECK (state IN ('pending', 'approved', 'rejected')),
  submitted_at BIGINT NOT NULL,
  reviewed_at BIGINT,
  reviewer_label TEXT,
  review_note TEXT NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS manual_review_queue_pending ON manual_review_queue(state, submitted_at ASC);

CREATE TABLE IF NOT EXISTS backup_runs (
  id TEXT PRIMARY KEY,
  started_at BIGINT NOT NULL,
  finished_at BIGINT,
  state TEXT NOT NULL CHECK (state IN ('running', 'ok', 'error')),
  local_path TEXT NOT NULL,
  local_sha256 CHAR(64),
  remote_target TEXT,
  remote_sha256 CHAR(64),
  byte_length BIGINT,
  archive_verified_at BIGINT,
  restore_verified_at BIGINT,
  error_code TEXT,
  details JSONB NOT NULL DEFAULT '{}'::jsonb
);
CREATE INDEX IF NOT EXISTS backup_runs_recent ON backup_runs(started_at DESC);

CREATE TABLE IF NOT EXISTS system_health_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  component TEXT NOT NULL,
  severity TEXT NOT NULL CHECK (severity IN ('info', 'warning', 'critical')),
  event_code TEXT NOT NULL,
  occurred_at BIGINT NOT NULL,
  resolved_at BIGINT,
  details JSONB NOT NULL DEFAULT '{}'::jsonb
);
CREATE INDEX IF NOT EXISTS system_health_events_open ON system_health_events(severity, occurred_at DESC) WHERE resolved_at IS NULL;

CREATE TABLE IF NOT EXISTS data_migration_runs (
  id TEXT PRIMARY KEY,
  source_id TEXT NOT NULL,
  started_at BIGINT NOT NULL,
  finished_at BIGINT NOT NULL,
  state TEXT NOT NULL CHECK (state IN ('planned', 'applied', 'verified', 'error')),
  source_sha256 CHAR(64),
  table_counts JSONB NOT NULL DEFAULT '{}'::jsonb,
  row_checksums JSONB NOT NULL DEFAULT '{}'::jsonb,
  error_code TEXT,
  details JSONB NOT NULL DEFAULT '{}'::jsonb
);
CREATE INDEX IF NOT EXISTS data_migration_runs_recent ON data_migration_runs(started_at DESC);

INSERT INTO schema_migrations(version)
VALUES ('002_first_party_operations')
ON CONFLICT (version) DO NOTHING;

COMMIT;
