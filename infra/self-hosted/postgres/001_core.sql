BEGIN;

CREATE TABLE IF NOT EXISTS schema_migrations (
  version TEXT PRIMARY KEY,
  applied_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS members (
  id TEXT PRIMARY KEY,
  handle TEXT NOT NULL,
  token_hash CHAR(64) NOT NULL,
  created_at BIGINT NOT NULL,
  last_post_at BIGINT NOT NULL DEFAULT 0,
  last_reply_at BIGINT NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX IF NOT EXISTS members_handle_ci_unique ON members (lower(handle));
CREATE UNIQUE INDEX IF NOT EXISTS members_token_hash_unique ON members (token_hash);

CREATE TABLE IF NOT EXISTS posts (
  id TEXT PRIMARY KEY,
  exam_id TEXT NOT NULL,
  member_id TEXT NOT NULL REFERENCES members(id) ON DELETE CASCADE,
  tag TEXT NOT NULL,
  content TEXT NOT NULL,
  created_at BIGINT NOT NULL,
  hidden SMALLINT NOT NULL DEFAULT 0 CHECK (hidden IN (0, 1))
);
CREATE INDEX IF NOT EXISTS posts_room_created ON posts (exam_id, created_at DESC);
CREATE INDEX IF NOT EXISTS posts_member_created ON posts (member_id, created_at DESC);

CREATE TABLE IF NOT EXISTS replies (
  id TEXT PRIMARY KEY,
  post_id TEXT NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
  member_id TEXT NOT NULL REFERENCES members(id) ON DELETE CASCADE,
  content TEXT NOT NULL,
  created_at BIGINT NOT NULL,
  hidden SMALLINT NOT NULL DEFAULT 0 CHECK (hidden IN (0, 1))
);
CREATE INDEX IF NOT EXISTS replies_post_created ON replies (post_id, created_at ASC);
CREATE INDEX IF NOT EXISTS replies_member_created ON replies (member_id, created_at DESC);

CREATE TABLE IF NOT EXISTS votes (
  post_id TEXT NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
  member_id TEXT NOT NULL REFERENCES members(id) ON DELETE CASCADE,
  created_at BIGINT NOT NULL,
  PRIMARY KEY (post_id, member_id)
);
CREATE INDEX IF NOT EXISTS votes_member ON votes (member_id, created_at DESC);

CREATE TABLE IF NOT EXISTS reports (
  id TEXT PRIMARY KEY,
  target_type TEXT NOT NULL CHECK (target_type IN ('post', 'reply')),
  target_id TEXT NOT NULL,
  reporter_id TEXT NOT NULL REFERENCES members(id) ON DELETE CASCADE,
  reason TEXT NOT NULL CHECK (reason IN ('spam', 'harassment', 'personal_information', 'misinformation', 'other')),
  created_at BIGINT NOT NULL,
  UNIQUE (target_type, target_id, reporter_id)
);
CREATE INDEX IF NOT EXISTS reports_created ON reports (created_at ASC);

CREATE TABLE IF NOT EXISTS moderation_actions (
  id TEXT PRIMARY KEY,
  target_type TEXT NOT NULL CHECK (target_type IN ('post', 'reply')),
  target_id TEXT NOT NULL,
  action TEXT NOT NULL CHECK (action IN ('hide', 'restore', 'dismiss')),
  reason TEXT NOT NULL,
  created_at BIGINT NOT NULL,
  admin_label TEXT NOT NULL DEFAULT 'founder'
);
CREATE INDEX IF NOT EXISTS moderation_actions_recent ON moderation_actions (created_at DESC);

CREATE TABLE IF NOT EXISTS portal_status (
  source_id TEXT PRIMARY KEY,
  status TEXT NOT NULL CHECK (status IN ('reachable', 'restricted', 'unconfirmed')),
  http_status INTEGER,
  checked_at BIGINT NOT NULL,
  latency_ms INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS portal_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_id TEXT NOT NULL,
  status TEXT NOT NULL CHECK (status IN ('reachable', 'restricted', 'unconfirmed')),
  checked_at BIGINT NOT NULL,
  http_status INTEGER,
  latency_ms INTEGER
);
CREATE INDEX IF NOT EXISTS portal_history_source_time ON portal_history (source_id, checked_at DESC);

CREATE TABLE IF NOT EXISTS official_job_notices (
  id TEXT PRIMARY KEY,
  source_id TEXT NOT NULL,
  source_ref TEXT NOT NULL,
  title TEXT NOT NULL,
  employer TEXT NOT NULL,
  country TEXT NOT NULL,
  region TEXT NOT NULL DEFAULT '',
  stream TEXT NOT NULL DEFAULT 'Unclassified',
  apply_url TEXT NOT NULL,
  source_page TEXT NOT NULL,
  published_at TEXT,
  closing_at TEXT NOT NULL,
  first_seen_at BIGINT NOT NULL,
  last_seen_at BIGINT NOT NULL,
  evidence_sha256 CHAR(64) NOT NULL,
  review_state TEXT NOT NULL DEFAULT 'official_feed_unreviewed'
    CHECK (review_state IN ('official_feed_unreviewed', 'founder_reviewed', 'rejected')),
  life_status TEXT NOT NULL DEFAULT 'open'
    CHECK (life_status IN ('open', 'expired', 'withdrawn')),
  jurisdiction_code TEXT NOT NULL DEFAULT '',
  jurisdiction_name TEXT NOT NULL DEFAULT '',
  government_tier TEXT NOT NULL DEFAULT 'unclassified',
  employer_type TEXT NOT NULL DEFAULT 'unclassified',
  UNIQUE (source_id, source_ref)
);
CREATE INDEX IF NOT EXISTS notices_recent ON official_job_notices (life_status, closing_at, first_seen_at DESC);
CREATE INDEX IF NOT EXISTS notices_source ON official_job_notices (source_id, last_seen_at DESC);
CREATE INDEX IF NOT EXISTS official_notices_jurisdiction
  ON official_job_notices (country, jurisdiction_code, government_tier, life_status, closing_at);

CREATE TABLE IF NOT EXISTS source_ingest_runs (
  id TEXT PRIMARY KEY,
  source_id TEXT NOT NULL,
  started_at BIGINT NOT NULL,
  finished_at BIGINT NOT NULL,
  state TEXT NOT NULL CHECK (state IN ('ok', 'rejected', 'error')),
  http_status INTEGER,
  received INTEGER NOT NULL DEFAULT 0,
  accepted INTEGER NOT NULL DEFAULT 0,
  discarded INTEGER NOT NULL DEFAULT 0,
  error_code TEXT,
  details TEXT NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS ingest_runs_source ON source_ingest_runs (source_id, finished_at DESC);

CREATE TABLE IF NOT EXISTS source_feed_cursors (
  source_id TEXT PRIMARY KEY,
  next_page INTEGER NOT NULL DEFAULT 1 CHECK (next_page > 0),
  last_total_pages INTEGER NOT NULL DEFAULT 1 CHECK (last_total_pages > 0),
  last_success_at BIGINT
);

CREATE TABLE IF NOT EXISTS notice_revisions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  notice_id TEXT NOT NULL,
  source_id TEXT NOT NULL,
  observed_at BIGINT NOT NULL,
  old_title TEXT NOT NULL,
  new_title TEXT NOT NULL,
  old_closing_at TEXT NOT NULL,
  new_closing_at TEXT NOT NULL,
  old_hash CHAR(64) NOT NULL,
  new_hash CHAR(64) NOT NULL
);
CREATE INDEX IF NOT EXISTS revision_seen ON notice_revisions (observed_at DESC);
CREATE INDEX IF NOT EXISTS revision_source ON notice_revisions (source_id, observed_at DESC);

CREATE TABLE IF NOT EXISTS scheduler_runs (
  slot TEXT PRIMARY KEY,
  task TEXT NOT NULL CHECK (task IN ('portals', 'uk', 'manitoba')),
  state TEXT NOT NULL CHECK (state IN ('running', 'ok', 'error')),
  started_at BIGINT NOT NULL,
  finished_at BIGINT,
  error_code TEXT,
  details TEXT NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS scheduler_runs_recent ON scheduler_runs (started_at DESC);

CREATE OR REPLACE FUNCTION globalgov_capture_notice_revision()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  IF OLD.evidence_sha256 IS DISTINCT FROM NEW.evidence_sha256 THEN
    INSERT INTO notice_revisions (
      notice_id, source_id, observed_at, old_title, new_title,
      old_closing_at, new_closing_at, old_hash, new_hash
    ) VALUES (
      NEW.id, NEW.source_id,
      floor(extract(epoch FROM clock_timestamp()) * 1000)::BIGINT,
      OLD.title, NEW.title, OLD.closing_at, NEW.closing_at,
      OLD.evidence_sha256, NEW.evidence_sha256
    );
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS capture_official_notice_revisions ON official_job_notices;
CREATE TRIGGER capture_official_notice_revisions
AFTER UPDATE OF evidence_sha256 ON official_job_notices
FOR EACH ROW
EXECUTE FUNCTION globalgov_capture_notice_revision();

INSERT INTO schema_migrations(version)
VALUES ('001_core')
ON CONFLICT (version) DO NOTHING;

COMMIT;
